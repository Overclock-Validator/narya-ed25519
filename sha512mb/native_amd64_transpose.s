// TRANSPOSE8 converts eight ZMM rows into eight ZMM columns. Inputs R0..R7
// are destroyed; outputs O0..O7 must not alias scratch T0..T7.
#define TRANSPOSE8(R0, R1, R2, R3, R4, R5, R6, R7, O0, O1, O2, O3, O4, O5, O6, O7, T0, T1, T2, T3, T4, T5, T6, T7) \
	VSHUFI64X2 $0x88, R2, R0, T0; \
	VSHUFI64X2 $0x88, R3, R1, T1; \
	VSHUFI64X2 $0xdd, R2, R0, T2; \
	VSHUFI64X2 $0xdd, R3, R1, T3; \
	VSHUFI64X2 $0x88, R6, R4, T4; \
	VSHUFI64X2 $0x88, R7, R5, T5; \
	VSHUFI64X2 $0xdd, R6, R4, T6; \
	VSHUFI64X2 $0xdd, R7, R5, T7; \
	VSHUFI64X2 $0x88, T4, T0, R0; \
	VSHUFI64X2 $0x88, T5, T1, R1; \
	VSHUFI64X2 $0x88, T6, T2, R2; \
	VSHUFI64X2 $0x88, T7, T3, R3; \
	VSHUFI64X2 $0xdd, T4, T0, R4; \
	VSHUFI64X2 $0xdd, T5, T1, R5; \
	VSHUFI64X2 $0xdd, T6, T2, R6; \
	VSHUFI64X2 $0xdd, T7, T3, R7; \
	VPUNPCKLQDQ R1, R0, O0;       \
	VPUNPCKHQDQ R1, R0, O1;       \
	VPUNPCKLQDQ R3, R2, O2;       \
	VPUNPCKHQDQ R3, R2, O3;       \
	VPUNPCKLQDQ R5, R4, O4;       \
	VPUNPCKHQDQ R5, R4, O5;       \
	VPUNPCKLQDQ R7, R6, O6;       \
	VPUNPCKHQDQ R7, R6, O7

// Each 128-bit lane reverses the bytes of its two uint64 words.
DATA ·nativeByteSwapMaskX8+0(SB)/8,  $0x0001020304050607
DATA ·nativeByteSwapMaskX8+8(SB)/8,  $0x08090a0b0c0d0e0f
DATA ·nativeByteSwapMaskX8+16(SB)/8, $0x0001020304050607
DATA ·nativeByteSwapMaskX8+24(SB)/8, $0x08090a0b0c0d0e0f
DATA ·nativeByteSwapMaskX8+32(SB)/8, $0x0001020304050607
DATA ·nativeByteSwapMaskX8+40(SB)/8, $0x08090a0b0c0d0e0f
DATA ·nativeByteSwapMaskX8+48(SB)/8, $0x0001020304050607
DATA ·nativeByteSwapMaskX8+56(SB)/8, $0x08090a0b0c0d0e0f
GLOBL ·nativeByteSwapMaskX8(SB), RODATA|NOPTR, $64

// func nativeTransposeX8(block *nativeBlockX8, raw *[nativeX8Width][128]byte)
//
// Requires AVX-512F and AVX-512BW. raw and block must not overlap.
TEXT ·nativeTransposeX8(SB), NOSPLIT, $0-16
	MOVQ block+0(FP), DI
	MOVQ raw+8(FP), SI
	VMOVDQU64 ·nativeByteSwapMaskX8(SB), Z31

	VMOVDQU64   0(SI), Z0
	VMOVDQU64 128(SI), Z1
	VMOVDQU64 256(SI), Z2
	VMOVDQU64 384(SI), Z3
	VMOVDQU64 512(SI), Z4
	VMOVDQU64 640(SI), Z5
	VMOVDQU64 768(SI), Z6
	VMOVDQU64 896(SI), Z7
	VPSHUFB Z31, Z0, Z0
	VPSHUFB Z31, Z1, Z1
	VPSHUFB Z31, Z2, Z2
	VPSHUFB Z31, Z3, Z3
	VPSHUFB Z31, Z4, Z4
	VPSHUFB Z31, Z5, Z5
	VPSHUFB Z31, Z6, Z6
	VPSHUFB Z31, Z7, Z7
	TRANSPOSE8(Z0, Z1, Z2, Z3, Z4, Z5, Z6, Z7, Z16, Z17, Z18, Z19, Z20, Z21, Z22, Z23, Z8, Z9, Z10, Z11, Z12, Z13, Z14, Z15)
	VMOVDQU64 Z16,   0(DI)
	VMOVDQU64 Z17,  64(DI)
	VMOVDQU64 Z18, 128(DI)
	VMOVDQU64 Z19, 192(DI)
	VMOVDQU64 Z20, 256(DI)
	VMOVDQU64 Z21, 320(DI)
	VMOVDQU64 Z22, 384(DI)
	VMOVDQU64 Z23, 448(DI)

	VMOVDQU64  64(SI), Z0
	VMOVDQU64 192(SI), Z1
	VMOVDQU64 320(SI), Z2
	VMOVDQU64 448(SI), Z3
	VMOVDQU64 576(SI), Z4
	VMOVDQU64 704(SI), Z5
	VMOVDQU64 832(SI), Z6
	VMOVDQU64 960(SI), Z7
	VPSHUFB Z31, Z0, Z0
	VPSHUFB Z31, Z1, Z1
	VPSHUFB Z31, Z2, Z2
	VPSHUFB Z31, Z3, Z3
	VPSHUFB Z31, Z4, Z4
	VPSHUFB Z31, Z5, Z5
	VPSHUFB Z31, Z6, Z6
	VPSHUFB Z31, Z7, Z7
	TRANSPOSE8(Z0, Z1, Z2, Z3, Z4, Z5, Z6, Z7, Z16, Z17, Z18, Z19, Z20, Z21, Z22, Z23, Z8, Z9, Z10, Z11, Z12, Z13, Z14, Z15)
	VMOVDQU64 Z16, 512(DI)
	VMOVDQU64 Z17, 576(DI)
	VMOVDQU64 Z18, 640(DI)
	VMOVDQU64 Z19, 704(DI)
	VMOVDQU64 Z20, 768(DI)
	VMOVDQU64 Z21, 832(DI)
	VMOVDQU64 Z22, 896(DI)
	VMOVDQU64 Z23, 960(DI)
	VZEROUPPER
	RET

// func nativeTransposePointersX8(block *nativeBlockX8, ptrs *[nativeX8Width]*byte)
//
// Requires AVX-512F and AVX-512BW. Every pointer must address at least 128
// readable bytes. This is the direct full-block counterpart of
// nativeTransposeX8 and avoids copying contiguous message blocks through the
// temporary raw matrix.
TEXT ·nativeTransposePointersX8(SB), NOSPLIT, $0-16
	MOVQ block+0(FP), DI
	MOVQ ptrs+8(FP), SI
	MOVQ  0(SI), AX
	MOVQ  8(SI), CX
	MOVQ 16(SI), DX
	MOVQ 24(SI), BX
	MOVQ 32(SI), R8
	MOVQ 40(SI), R9
	MOVQ 48(SI), R10
	MOVQ 56(SI), R11
	VMOVDQU64 ·nativeByteSwapMaskX8(SB), Z31

	VMOVDQU64 0(AX), Z0
	VMOVDQU64 0(CX), Z1
	VMOVDQU64 0(DX), Z2
	VMOVDQU64 0(BX), Z3
	VMOVDQU64 0(R8), Z4
	VMOVDQU64 0(R9), Z5
	VMOVDQU64 0(R10), Z6
	VMOVDQU64 0(R11), Z7
	VPSHUFB Z31, Z0, Z0
	VPSHUFB Z31, Z1, Z1
	VPSHUFB Z31, Z2, Z2
	VPSHUFB Z31, Z3, Z3
	VPSHUFB Z31, Z4, Z4
	VPSHUFB Z31, Z5, Z5
	VPSHUFB Z31, Z6, Z6
	VPSHUFB Z31, Z7, Z7
	TRANSPOSE8(Z0, Z1, Z2, Z3, Z4, Z5, Z6, Z7, Z16, Z17, Z18, Z19, Z20, Z21, Z22, Z23, Z8, Z9, Z10, Z11, Z12, Z13, Z14, Z15)
