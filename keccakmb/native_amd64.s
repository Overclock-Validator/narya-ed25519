// Eight Keccak-f[1600] instances, one per 64-bit lane of a ZMM register.
// Word i of the lane-sliced state (lane (i%5, i/5)) lives in Z<i> for the
// whole permutation. theta's column parities use Z25..Z29, which are dead
// after theta and serve as chi's scratch; Z30 is rho and pi's saved word. Z31
// is never touched by the permutation, so the absorb kernel keeps its vector
// of block pointers there across blocks. rho and pi run as one 24-step chain
// along pi's single 24-cycle in reverse, so every destination is written
// after its old value was read and the register assignment is the same at
// the start of every round.
//
// VPTERNLOGQ $imm, C, B, A computes A = f(A, B, C), with truth-table index
// 4A + 2B + C. 0x96 is A ^ B ^ C; 0xd2 is A ^ (~B & C), the chi step.
//
// Generated by scripts/gen_keccakmb_amd64.py; do not edit. The permutation
// body is identical in all three functions.

// COLUMN sets c to the parity of one column.
#define COLUMN(a0, a1, a2, a3, a4, c) \
	VPXORQ     a1, a0, c;              \
	VPTERNLOGQ $0x96, a3, a2, c;       \
	VPXORQ     a4, c, c

// THETA_X applies D[x] = C[x-1] ^ rot(C[x+1], 1) to the five lanes of column x.
#define THETA_X(cprev, cnext, a0, a1, a2, a3, a4) \
	VPROLQ     $1, cnext, Z30;                     \
	VPTERNLOGQ $0x96, Z30, cprev, a0;              \
	VPTERNLOGQ $0x96, Z30, cprev, a1;              \
	VPTERNLOGQ $0x96, Z30, cprev, a2;              \
	VPTERNLOGQ $0x96, Z30, cprev, a3;              \
	VPTERNLOGQ $0x96, Z30, cprev, a4

// CHI_ROW applies a[x] ^= ~a[x+1] & a[x+2] to one row, keeping the original
// a[0] and a[1] in Z25 and Z26 for the wrap-around terms.
#define CHI_ROW(r0, r1, r2, r3, r4) \
	VMOVDQA64  r0, Z25;              \
	VMOVDQA64  r1, Z26;              \
	VPTERNLOGQ $0xd2, r2, r1, r0;    \
	VPTERNLOGQ $0xd2, r3, r2, r1;    \
	VPTERNLOGQ $0xd2, r4, r3, r2;    \
	VPTERNLOGQ $0xd2, Z25, r4, r3;   \
	VPTERNLOGQ $0xd2, Z26, Z25, r4

// SCATTER_WORD stores word w of every lane to its output block. Z31 holds
// the lane offsets 0, 200, ..., 1400 into the [Lanes][200]byte buffer at BX.
#define SCATTER_WORD(off, z) \
	KXNORW      K1, K1, K1; \
	VPSCATTERQQ z, K1, off(BX)(Z31*1)

// GATHER_XOR XORs word w of every lane's block into state register z. Z31
// holds the eight block addresses and R9 is zero, so lane j loads from
// Z31[j] + 8w. A gather merges into its destination and clears its mask, so
// the destination t is zeroed first (a dependency-breaking idiom) and the
// caller rotates t over Z25..Z30, letting consecutive gathers overlap.
#define GATHER_XOR(off, z, t) \
	VPXORQ     t, t, t;        \
	KXNORW     K1, K1, K1;     \
	VPGATHERQQ off(R9)(Z31*1), K1, t; \
	VPXORQ     t, z, z

// func permuteX8Native(s *StateX8)
TEXT ·permuteX8Native(SB), NOSPLIT, $0-8
	MOVQ s+0(FP), AX
	VMOVDQU64 0(AX), Z0
	VMOVDQU64 64(AX), Z1
	VMOVDQU64 128(AX), Z2
	VMOVDQU64 192(AX), Z3
	VMOVDQU64 256(AX), Z4
	VMOVDQU64 320(AX), Z5
	VMOVDQU64 384(AX), Z6
	VMOVDQU64 448(AX), Z7
	VMOVDQU64 512(AX), Z8
	VMOVDQU64 576(AX), Z9
	VMOVDQU64 640(AX), Z10
	VMOVDQU64 704(AX), Z11
	VMOVDQU64 768(AX), Z12
	VMOVDQU64 832(AX), Z13
	VMOVDQU64 896(AX), Z14
	VMOVDQU64 960(AX), Z15
	VMOVDQU64 1024(AX), Z16
	VMOVDQU64 1088(AX), Z17
	VMOVDQU64 1152(AX), Z18
	VMOVDQU64 1216(AX), Z19
	VMOVDQU64 1280(AX), Z20
	VMOVDQU64 1344(AX), Z21
	VMOVDQU64 1408(AX), Z22
	VMOVDQU64 1472(AX), Z23
	VMOVDQU64 1536(AX), Z24
	LEAQ ·roundConstants(SB), CX
	MOVQ $24, DX

permround:
	// theta
	COLUMN(Z0, Z5, Z10, Z15, Z20, Z25)
	COLUMN(Z1, Z6, Z11, Z16, Z21, Z26)
	COLUMN(Z2, Z7, Z12, Z17, Z22, Z27)
	COLUMN(Z3, Z8, Z13, Z18, Z23, Z28)
	COLUMN(Z4, Z9, Z14, Z19, Z24, Z29)
	THETA_X(Z29, Z26, Z0, Z5, Z10, Z15, Z20)
	THETA_X(Z25, Z27, Z1, Z6, Z11, Z16, Z21)
	THETA_X(Z26, Z28, Z2, Z7, Z12, Z17, Z22)
	THETA_X(Z27, Z29, Z3, Z8, Z13, Z18, Z23)
	THETA_X(Z28, Z25, Z4, Z9, Z14, Z19, Z24)

	// rho and pi along the 24-cycle, newest destination first
	VMOVDQA64 Z1, Z30
	VPROLQ $44, Z6, Z1
	VPROLQ $20, Z9, Z6
	VPROLQ $61, Z22, Z9
	VPROLQ $39, Z14, Z22
	VPROLQ $18, Z20, Z14
	VPROLQ $62, Z2, Z20
	VPROLQ $43, Z12, Z2
	VPROLQ $25, Z13, Z12
	VPROLQ $8, Z19, Z13
	VPROLQ $56, Z23, Z19
	VPROLQ $41, Z15, Z23
	VPROLQ $27, Z4, Z15
	VPROLQ $14, Z24, Z4
	VPROLQ $2, Z21, Z24
	VPROLQ $55, Z8, Z21
	VPROLQ $45, Z16, Z8
	VPROLQ $36, Z5, Z16
	VPROLQ $28, Z3, Z5
	VPROLQ $21, Z18, Z3
	VPROLQ $15, Z17, Z18
	VPROLQ $10, Z11, Z17
	VPROLQ $6, Z7, Z11
	VPROLQ $3, Z10, Z7
	VPROLQ $1, Z30, Z10

	// chi
	CHI_ROW(Z0, Z1, Z2, Z3, Z4)
	CHI_ROW(Z5, Z6, Z7, Z8, Z9)
	CHI_ROW(Z10, Z11, Z12, Z13, Z14)
	CHI_ROW(Z15, Z16, Z17, Z18, Z19)
	CHI_ROW(Z20, Z21, Z22, Z23, Z24)

	// iota
	VPBROADCASTQ (CX), Z30
	VPXORQ       Z30, Z0, Z0
	ADDQ         $8, CX
	DECQ         DX
	JNZ          permround

	VMOVDQU64 Z0, 0(AX)
	VMOVDQU64 Z1, 64(AX)
	VMOVDQU64 Z2, 128(AX)
	VMOVDQU64 Z3, 192(AX)
	VMOVDQU64 Z4, 256(AX)
	VMOVDQU64 Z5, 320(AX)
	VMOVDQU64 Z6, 384(AX)
	VMOVDQU64 Z7, 448(AX)
	VMOVDQU64 Z8, 512(AX)
	VMOVDQU64 Z9, 576(AX)
	VMOVDQU64 Z10, 640(AX)
	VMOVDQU64 Z11, 704(AX)
	VMOVDQU64 Z12, 768(AX)
	VMOVDQU64 Z13, 832(AX)
	VMOVDQU64 Z14, 896(AX)
	VMOVDQU64 Z15, 960(AX)
	VMOVDQU64 Z16, 1024(AX)
	VMOVDQU64 Z17, 1088(AX)
	VMOVDQU64 Z18, 1152(AX)
	VMOVDQU64 Z19, 1216(AX)
	VMOVDQU64 Z20, 1280(AX)
	VMOVDQU64 Z21, 1344(AX)
	VMOVDQU64 Z22, 1408(AX)
	VMOVDQU64 Z23, 1472(AX)
	VMOVDQU64 Z24, 1536(AX)
	VZEROUPPER
	RET

// func absorbX8Native(s *StateX8, ptrs *[Lanes]*byte, strides *[Lanes]uint64, words, blocks int)
//
// For each of blocks blocks: XOR words 64-bit words from every lane's block
// pointer into the state, permute, and advance each pointer by its stride.
// words is 17 (rate 136) or 21 (rate 168) and blocks is at least 1; the Go
// caller checks both. The advanced pointers live only in Z31 and are never
// written back, so no pointer is stored without a write barrier.
TEXT ·absorbX8Native(SB), NOSPLIT, $0-40
	MOVQ s+0(FP), AX
	MOVQ ptrs+8(FP), BX
	MOVQ strides+16(FP), SI
	MOVQ words+24(FP), DI
	MOVQ blocks+32(FP), R8
	VMOVDQU64 0(AX), Z0
	VMOVDQU64 64(AX), Z1
	VMOVDQU64 128(AX), Z2
	VMOVDQU64 192(AX), Z3
	VMOVDQU64 256(AX), Z4
	VMOVDQU64 320(AX), Z5
	VMOVDQU64 384(AX), Z6
	VMOVDQU64 448(AX), Z7
	VMOVDQU64 512(AX), Z8
	VMOVDQU64 576(AX), Z9
	VMOVDQU64 640(AX), Z10
	VMOVDQU64 704(AX), Z11
	VMOVDQU64 768(AX), Z12
	VMOVDQU64 832(AX), Z13
	VMOVDQU64 896(AX), Z14
	VMOVDQU64 960(AX), Z15
	VMOVDQU64 1024(AX), Z16
	VMOVDQU64 1088(AX), Z17
	VMOVDQU64 1152(AX), Z18
	VMOVDQU64 1216(AX), Z19
	VMOVDQU64 1280(AX), Z20
	VMOVDQU64 1344(AX), Z21
	VMOVDQU64 1408(AX), Z22
	VMOVDQU64 1472(AX), Z23
	VMOVDQU64 1536(AX), Z24
	VMOVDQU64 (BX), Z31
	XORQ R9, R9

block:
	GATHER_XOR(0, Z0, Z25)
	GATHER_XOR(8, Z1, Z26)
	GATHER_XOR(16, Z2, Z27)
	GATHER_XOR(24, Z3, Z28)
	GATHER_XOR(32, Z4, Z29)
	GATHER_XOR(40, Z5, Z30)
	GATHER_XOR(48, Z6, Z25)
	GATHER_XOR(56, Z7, Z26)
	GATHER_XOR(64, Z8, Z27)
	GATHER_XOR(72, Z9, Z28)
	GATHER_XOR(80, Z10, Z29)
	GATHER_XOR(88, Z11, Z30)
	GATHER_XOR(96, Z12, Z25)
	GATHER_XOR(104, Z13, Z26)
	GATHER_XOR(112, Z14, Z27)
	GATHER_XOR(120, Z15, Z28)
	GATHER_XOR(128, Z16, Z29)
	CMPQ DI, $17
	JEQ  absorbed
	GATHER_XOR(136, Z17, Z30)
	GATHER_XOR(144, Z18, Z25)
	GATHER_XOR(152, Z19, Z26)
	GATHER_XOR(160, Z20, Z27)

absorbed:
	VPADDQ (SI), Z31, Z31
	LEAQ ·roundConstants(SB), CX
	MOVQ $24, DX

absorbround:
	// theta
	COLUMN(Z0, Z5, Z10, Z15, Z20, Z25)
	COLUMN(Z1, Z6, Z11, Z16, Z21, Z26)
	COLUMN(Z2, Z7, Z12, Z17, Z22, Z27)
	COLUMN(Z3, Z8, Z13, Z18, Z23, Z28)
	COLUMN(Z4, Z9, Z14, Z19, Z24, Z29)
	THETA_X(Z29, Z26, Z0, Z5, Z10, Z15, Z20)
	THETA_X(Z25, Z27, Z1, Z6, Z11, Z16, Z21)
	THETA_X(Z26, Z28, Z2, Z7, Z12, Z17, Z22)
	THETA_X(Z27, Z29, Z3, Z8, Z13, Z18, Z23)
	THETA_X(Z28, Z25, Z4, Z9, Z14, Z19, Z24)

	// rho and pi along the 24-cycle, newest destination first
	VMOVDQA64 Z1, Z30
	VPROLQ $44, Z6, Z1
	VPROLQ $20, Z9, Z6
	VPROLQ $61, Z22, Z9
	VPROLQ $39, Z14, Z22
	VPROLQ $18, Z20, Z14
	VPROLQ $62, Z2, Z20
	VPROLQ $43, Z12, Z2
	VPROLQ $25, Z13, Z12
	VPROLQ $8, Z19, Z13
	VPROLQ $56, Z23, Z19
	VPROLQ $41, Z15, Z23
	VPROLQ $27, Z4, Z15
	VPROLQ $14, Z24, Z4
	VPROLQ $2, Z21, Z24
	VPROLQ $55, Z8, Z21
	VPROLQ $45, Z16, Z8
	VPROLQ $36, Z5, Z16
	VPROLQ $28, Z3, Z5
	VPROLQ $21, Z18, Z3
	VPROLQ $15, Z17, Z18
	VPROLQ $10, Z11, Z17
	VPROLQ $6, Z7, Z11
	VPROLQ $3, Z10, Z7
	VPROLQ $1, Z30, Z10

	// chi
	CHI_ROW(Z0, Z1, Z2, Z3, Z4)
	CHI_ROW(Z5, Z6, Z7, Z8, Z9)
	CHI_ROW(Z10, Z11, Z12, Z13, Z14)
	CHI_ROW(Z15, Z16, Z17, Z18, Z19)
	CHI_ROW(Z20, Z21, Z22, Z23, Z24)

	// iota
	VPBROADCASTQ (CX), Z30
	VPXORQ       Z30, Z0, Z0
	ADDQ         $8, CX
	DECQ         DX
	JNZ          absorbround
	DECQ R8
	JNZ  block

	VMOVDQU64 Z0, 0(AX)
	VMOVDQU64 Z1, 64(AX)
	VMOVDQU64 Z2, 128(AX)
	VMOVDQU64 Z3, 192(AX)
	VMOVDQU64 Z4, 256(AX)
	VMOVDQU64 Z5, 320(AX)
	VMOVDQU64 Z6, 384(AX)
	VMOVDQU64 Z7, 448(AX)
	VMOVDQU64 Z8, 512(AX)
	VMOVDQU64 Z9, 576(AX)
	VMOVDQU64 Z10, 640(AX)
	VMOVDQU64 Z11, 704(AX)
	VMOVDQU64 Z12, 768(AX)
	VMOVDQU64 Z13, 832(AX)
	VMOVDQU64 Z14, 896(AX)
	VMOVDQU64 Z15, 960(AX)
	VMOVDQU64 Z16, 1024(AX)
	VMOVDQU64 Z17, 1088(AX)
	VMOVDQU64 Z18, 1152(AX)
	VMOVDQU64 Z19, 1216(AX)
	VMOVDQU64 Z20, 1280(AX)
	VMOVDQU64 Z21, 1344(AX)
	VMOVDQU64 Z22, 1408(AX)
	VMOVDQU64 Z23, 1472(AX)
	VMOVDQU64 Z24, 1536(AX)
	VZEROUPPER
	RET

// func squeezeX8Native(s *StateX8, out *[Lanes][200]byte, words, permute int)
