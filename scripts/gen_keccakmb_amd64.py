#!/usr/bin/env python3
"""Generates keccakmb/native_amd64.s.

Run from the repository root:

    python3 scripts/gen_keccakmb_amd64.py keccakmb/native_amd64.s

The pi lane cycle and rotation offsets are derived here from the FIPS 202
definitions and asserted against the standard tiny-keccak table.
"""
import sys

rho=[0,1,62,28,27,36,44,6,55,20,3,10,43,25,39,41,45,15,21,8,18,2,61,56,14]
def dest(i):
    x,y=i%5,i//5
    return y+5*((2*x+3*y)%5)
chain=[1]
while dest(chain[-1])!=1: chain.append(dest(chain[-1]))
piln=[dest(c) for c in chain]; rotc=[rho[c] for c in chain]
assert piln==[10,7,11,17,18,3,5,16,8,21,24,4,15,23,19,13,12,2,20,14,22,9,6,1]
L=[]
w=L.append
w('//go:build amd64\n\n#include "textflag.h"\n\n')
w('''// Eight Keccak-f[1600] instances, one per 64-bit lane of a ZMM register.
// Word i of the lane-sliced state (lane (i%5, i/5)) lives in Z<i> for the
// whole permutation. theta's column parities use Z25..Z29, which are dead
// after theta and serve as chi's scratch; Z30 is rho and pi's saved word. Z31
// is never touched by the permutation, so the absorb kernel keeps its vector
// of block pointers there across blocks. rho and pi run as one 24-step chain
// along pi's single 24-cycle in reverse, so every destination is written
// after its old value was read and the register assignment is the same at
// the start of every round.
//
// VPTERNLOGQ $imm, C, B, A computes A = f(A, B, C), with truth-table index
// 4A + 2B + C. 0x96 is A ^ B ^ C; 0xd2 is A ^ (~B & C), the chi step.
//
// Generated by scripts/gen_keccakmb_amd64.py; do not edit. The permutation
// body is identical in all three functions.

// COLUMN sets c to the parity of one column.
#define COLUMN(a0, a1, a2, a3, a4, c) \\
	VPXORQ     a1, a0, c;              \\
	VPTERNLOGQ $0x96, a3, a2, c;       \\
	VPXORQ     a4, c, c

// THETA_X applies D[x] = C[x-1] ^ rot(C[x+1], 1) to the five lanes of column x.
#define THETA_X(cprev, cnext, a0, a1, a2, a3, a4) \\
	VPROLQ     $1, cnext, Z30;                     \\
	VPTERNLOGQ $0x96, Z30, cprev, a0;              \\
	VPTERNLOGQ $0x96, Z30, cprev, a1;              \\
	VPTERNLOGQ $0x96, Z30, cprev, a2;              \\
	VPTERNLOGQ $0x96, Z30, cprev, a3;              \\
	VPTERNLOGQ $0x96, Z30, cprev, a4

// CHI_ROW applies a[x] ^= ~a[x+1] & a[x+2] to one row, keeping the original
// a[0] and a[1] in Z25 and Z26 for the wrap-around terms.
#define CHI_ROW(r0, r1, r2, r3, r4) \\
	VMOVDQA64  r0, Z25;              \\
	VMOVDQA64  r1, Z26;              \\
	VPTERNLOGQ $0xd2, r2, r1, r0;    \\
	VPTERNLOGQ $0xd2, r3, r2, r1;    \\
	VPTERNLOGQ $0xd2, r4, r3, r2;    \\
	VPTERNLOGQ $0xd2, Z25, r4, r3;   \\
	VPTERNLOGQ $0xd2, Z26, Z25, r4

// SCATTER_WORD stores word w of every active lane to its output block. Z31
// holds the lane offsets 0, 200, ..., 1400 into the [Lanes][200]byte buffer
// at BX, and K2 holds the active-lane mask. A scatter clears its mask, so K1
// is reloaded from K2 each time; inactive lanes are never written.
#define SCATTER_WORD(off, z) \\
	KMOVW       K2, K1; \\
	VPSCATTERQQ z, K1, off(BX)(Z31*1)

// GATHER_XOR XORs word w of every lane's block into state register z. Z31
// holds the eight block addresses and R9 is zero, so lane j loads from
// Z31[j] + 8w. A gather merges into its destination and clears its mask, so
// the destination t is zeroed first (a dependency-breaking idiom) and the
// caller rotates t over Z25..Z30, letting consecutive gathers overlap.
#define GATHER_XOR(off, z, t) \\
	VPXORQ     t, t, t;        \\
	KXNORW     K1, K1, K1;     \\
	VPGATHERQQ off(R9)(Z31*1), K1, t; \\
	VPXORQ     t, z, z

''')
def load():
    for i in range(25): w(f'\tVMOVDQU64 {64*i}(AX), Z{i}\n')
def store():
    for i in range(25): w(f'\tVMOVDQU64 Z{i}, {64*i}(AX)\n')
def perm(lbl):
    w(f'\tLEAQ ·roundConstants(SB), CX\n\tMOVQ $24, DX\n\n{lbl}:\n\t// theta\n')
    for x in range(5): w(f'\tCOLUMN(Z{x}, Z{x+5}, Z{x+10}, Z{x+15}, Z{x+20}, Z{25+x})\n')
    for x in range(5): w(f'\tTHETA_X(Z{25+(x+4)%5}, Z{25+(x+1)%5}, Z{x}, Z{x+5}, Z{x+10}, Z{x+15}, Z{x+20})\n')
    w('\n\t// rho and pi along the 24-cycle, newest destination first\n\tVMOVDQA64 Z1, Z30\n')
    for i in range(23,0,-1): w(f'\tVPROLQ ${rotc[i]}, Z{chain[i]}, Z{piln[i]}\n')
    w(f'\tVPROLQ ${rotc[0]}, Z30, Z{piln[0]}\n\n\t// chi\n')
    for y in range(5): w('\tCHI_ROW(' + ', '.join(f'Z{5*y+x}' for x in range(5)) + ')\n')
    w(f'''
	// iota
	VPBROADCASTQ (CX), Z30
	VPXORQ       Z30, Z0, Z0
	ADDQ         $8, CX
	DECQ         DX
	JNZ          {lbl}
''')
w('// func permuteX8Native(s *StateX8)\nTEXT ·permuteX8Native(SB), NOSPLIT, $0-8\n\tMOVQ s+0(FP), AX\n')
load(); perm('permround'); w('\n'); store(); w('\tVZEROUPPER\n\tRET\n\n')
w('''// func absorbX8Native(s *StateX8, ptrs *[Lanes]*byte, strides *[Lanes]uint64, words, blocks int)
//
// For each of blocks blocks: XOR words 64-bit words from every lane's block
// pointer into the state, permute, and advance each pointer by its stride.
// words is 17 (rate 136) or 21 (rate 168) and blocks is at least 1; the Go
// caller checks both. The advanced pointers live only in Z31 and are never
// written back, so no pointer is stored without a write barrier.
TEXT ·absorbX8Native(SB), NOSPLIT, $0-40
	MOVQ s+0(FP), AX
	MOVQ ptrs+8(FP), BX
	MOVQ strides+16(FP), SI
	MOVQ words+24(FP), DI
	MOVQ blocks+32(FP), R8
''')
load()
w('\tVMOVDQU64 (BX), Z31\n\tXORQ R9, R9\n\nblock:\n')
for i in range(17): w(f'\tGATHER_XOR({8*i}, Z{i}, Z{25+i%6})\n')
w('\tCMPQ DI, $17\n\tJEQ  absorbed\n')
for i in range(17,21): w(f'\tGATHER_XOR({8*i}, Z{i}, Z{25+i%6})\n')
w('\nabsorbed:\n\tVPADDQ (SI), Z31, Z31\n')
perm('absorbround')
w('\tDECQ R8\n\tJNZ  block\n\n')
store(); w('\tVZEROUPPER\n\tRET\n')
w('''
// func squeezeX8Native(s *StateX8, out *[Lanes][200]byte, words, permute, mask int)
//
// If permute is nonzero, permute s and store it. Then write the first words
// 64-bit words of every lane j whose bit is set in mask to out[j], leaving
// the other lanes of out untouched. words is 17 or 21.
TEXT ·squeezeX8Native(SB), NOSPLIT, $0-40
	MOVQ s+0(FP), AX
	MOVQ out+8(FP), BX
	MOVQ words+16(FP), DI
	MOVQ permute+24(FP), R8
	MOVQ mask+32(FP), R10
''')
load()
w('\tTESTQ R8, R8\n\tJZ    extract\n')
perm('squeezeround')
store()
w('\nextract:\n\tVMOVDQU64 ·laneOffsets(SB), Z31\n\tKMOVW     R10, K2\n')
for i in range(17): w(f'\tSCATTER_WORD({8*i}, Z{i})\n')
w('\tCMPQ DI, $17\n\tJEQ  squeezed\n')
for i in range(17,21): w(f'\tSCATTER_WORD({8*i}, Z{i})\n')
w('\nsqueezed:\n\tVZEROUPPER\n\tRET\n')
open(sys.argv[1],'w').write(''.join(L))
