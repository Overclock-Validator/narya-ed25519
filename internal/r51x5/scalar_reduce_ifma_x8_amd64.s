// Fold coefficient HIGH at radix position i >= 12 into positions i-12..i-7
// using 2^252 = 666643 + 470296*B + 654183*B^2 - 997805*B^3
//              + 136657*B^4 - 683901*B^5 (mod l), B=2^21.
// Z24..Z29 hold the six positive constants and Z30 is the sole temporary.
#define SCALAR_FOLD(HIGH, L0, L1, L2, L3, L4, L5) \
	VPMULLQ Z24, HIGH, Z30                             \
	VPADDQ  Z30, L0, L0                                \
	VPMULLQ Z25, HIGH, Z30                             \
	VPADDQ  Z30, L1, L1                                \
	VPMULLQ Z26, HIGH, Z30                             \
	VPADDQ  Z30, L2, L2                                \
	VPMULLQ Z27, HIGH, Z30                             \
	VPSUBQ  Z30, L3, L3                                \
	VPMULLQ Z28, HIGH, Z30                             \
	VPADDQ  Z30, L4, L4                                \
	VPMULLQ Z29, HIGH, Z30                             \
	VPSUBQ  Z30, L5, L5                                \
	VPXORQ  HIGH, HIGH, HIGH

// Center a signed radix-2^21 limb: carry=floor((limb+2^20)/2^21).
#define SCALAR_CARRY_ROUNDED(LIMB, NEXT) \
	VPADDQ Z31, LIMB, Z30                  \
	VPSRAQ $21, Z30, Z30                   \
	VPADDQ Z30, NEXT, NEXT                 \
	VPSLLQ $21, Z30, Z30                   \
	VPSUBQ Z30, LIMB, LIMB

// Final non-centering carry: carry=floor(limb/2^21).
#define SCALAR_CARRY(LIMB, NEXT) \
	VPSRAQ $21, LIMB, Z30       \
	VPADDQ Z30, NEXT, NEXT      \
	VPSLLQ $21, Z30, Z30       \
	VPSUBQ Z30, LIMB, LIMB

