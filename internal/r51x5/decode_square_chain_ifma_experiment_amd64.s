//go:build amd64 && !purego

#include "textflag.h"

#define CHAIN_SQUARE_MUL_PAIR(X, Y, L, H) \
	VPMADD52LUQ Y, X, L                    \
	VPMADD52HUQ Y, X, H

#define CHAIN_SQUARE_CLEAR(R) VPXORQ R, R, R

#define CHAIN_SQUARE_COMBINE_HIGH(H, L) \
	VPSLLQ $1, H, H                       \
	VPADDQ H, L, L

#define CHAIN_SQUARE_FOLD_MUL19(LO, HI, T, FOLD19) \
	VPMULLQ FOLD19, HI, T                         \
	VPADDQ T, LO, LO

#define CHAIN_SQUARE_NORMALIZE_5(IN0, IN1, IN2, IN3, IN4, MASK, C0, C1, C2, C3, C4, FOLD19) \
	VPSRLQ $51, IN0, C0                                                                        \
	VPSRLQ $51, IN1, C1                                                                        \
	VPSRLQ $51, IN2, C2                                                                        \
	VPSRLQ $51, IN3, C3                                                                        \
	VPSRLQ $51, IN4, C4                                                                        \
	VPANDQ MASK, IN0, IN0                                                                      \
	VPANDQ MASK, IN1, IN1                                                                      \
	VPANDQ MASK, IN2, IN2                                                                      \
	VPANDQ MASK, IN3, IN3                                                                      \
	VPANDQ MASK, IN4, IN4                                                                      \
	VPADDQ C0, IN1, IN1                                                                        \
	VPADDQ C1, IN2, IN2                                                                        \
	VPADDQ C2, IN3, IN3                                                                        \
	VPADDQ C3, IN4, IN4                                                                        \
	VPMADD52LUQ C4, FOLD19, IN0

// func ifmaRepeatedSquareNormalizedX4(out, x *LimbsX4, count int)
//
// Y0..Y4 retain the running field element. This is the exact four-lane form
// of the x8 chain below; all limb bounds and alias guarantees are identical.
TEXT ·ifmaRepeatedSquareNormalizedX4(SB), NOSPLIT, $0-24
	MOVQ out+0(FP), DI
	MOVQ x+8(FP), CX
	MOVQ count+16(FP), AX

	VMOVDQU64   0(CX), Y0
	VMOVDQU64  32(CX), Y1
	VMOVDQU64  64(CX), Y2
	VMOVDQU64  96(CX), Y3
	VMOVDQU64 128(CX), Y4
	TESTQ AX, AX
	JE chain_square_x4_store

	VPBROADCASTQ ·ifmaLimbMask51(SB), Y24
	VPBROADCASTQ ·ifmaFold19(SB), Y25

chain_square_x4_loop:
	CHAIN_SQUARE_CLEAR(Y5)
	CHAIN_SQUARE_CLEAR(Y6)
	CHAIN_SQUARE_CLEAR(Y7)
	CHAIN_SQUARE_CLEAR(Y8)
	CHAIN_SQUARE_CLEAR(Y9)
	CHAIN_SQUARE_CLEAR(Y10)
	CHAIN_SQUARE_CLEAR(Y11)
	CHAIN_SQUARE_CLEAR(Y12)
	CHAIN_SQUARE_CLEAR(Y13)
	CHAIN_SQUARE_CLEAR(Y14)
	CHAIN_SQUARE_CLEAR(Y15)
	CHAIN_SQUARE_CLEAR(Y16)
	CHAIN_SQUARE_CLEAR(Y17)
	CHAIN_SQUARE_CLEAR(Y18)
	CHAIN_SQUARE_CLEAR(Y19)
	CHAIN_SQUARE_CLEAR(Y20)
	CHAIN_SQUARE_CLEAR(Y21)
	CHAIN_SQUARE_CLEAR(Y22)

	CHAIN_SQUARE_MUL_PAIR(Y0, Y1, Y6,  Y15)
	CHAIN_SQUARE_MUL_PAIR(Y0, Y2, Y7,  Y16)
	CHAIN_SQUARE_MUL_PAIR(Y0, Y3, Y8,  Y17)
	CHAIN_SQUARE_MUL_PAIR(Y0, Y4, Y9,  Y18)
	CHAIN_SQUARE_MUL_PAIR(Y1, Y2, Y8,  Y17)
	CHAIN_SQUARE_MUL_PAIR(Y1, Y3, Y9,  Y18)
	CHAIN_SQUARE_MUL_PAIR(Y1, Y4, Y10, Y19)
	CHAIN_SQUARE_MUL_PAIR(Y2, Y3, Y10, Y19)
	CHAIN_SQUARE_MUL_PAIR(Y2, Y4, Y11, Y20)
	CHAIN_SQUARE_MUL_PAIR(Y3, Y4, Y12, Y21)

	VPSLLQ $1, Y6,  Y6
	VPSLLQ $1, Y7,  Y7
	VPSLLQ $1, Y8,  Y8
	VPSLLQ $1, Y9,  Y9
	VPSLLQ $1, Y10, Y10
	VPSLLQ $1, Y11, Y11
	VPSLLQ $1, Y12, Y12
	VPSLLQ $1, Y15, Y15
	VPSLLQ $1, Y16, Y16
	VPSLLQ $1, Y17, Y17
	VPSLLQ $1, Y18, Y18
	VPSLLQ $1, Y19, Y19
	VPSLLQ $1, Y20, Y20
	VPSLLQ $1, Y21, Y21

	CHAIN_SQUARE_MUL_PAIR(Y0, Y0, Y5,  Y14)
	CHAIN_SQUARE_MUL_PAIR(Y1, Y1, Y7,  Y16)
	CHAIN_SQUARE_MUL_PAIR(Y2, Y2, Y9,  Y18)
	CHAIN_SQUARE_MUL_PAIR(Y3, Y3, Y11, Y20)
	CHAIN_SQUARE_MUL_PAIR(Y4, Y4, Y13, Y22)

	CHAIN_SQUARE_COMBINE_HIGH(Y14, Y6)
	CHAIN_SQUARE_COMBINE_HIGH(Y15, Y7)
	CHAIN_SQUARE_COMBINE_HIGH(Y16, Y8)
	CHAIN_SQUARE_COMBINE_HIGH(Y17, Y9)
	CHAIN_SQUARE_COMBINE_HIGH(Y18, Y10)
	CHAIN_SQUARE_COMBINE_HIGH(Y19, Y11)
	CHAIN_SQUARE_COMBINE_HIGH(Y20, Y12)
	CHAIN_SQUARE_COMBINE_HIGH(Y21, Y13)
	VPSLLQ $1, Y22, Y22

	CHAIN_SQUARE_FOLD_MUL19(Y5, Y10, Y23, Y25)
	CHAIN_SQUARE_FOLD_MUL19(Y6, Y11, Y23, Y25)
	CHAIN_SQUARE_FOLD_MUL19(Y7, Y12, Y23, Y25)
	CHAIN_SQUARE_FOLD_MUL19(Y8, Y13, Y23, Y25)
	CHAIN_SQUARE_FOLD_MUL19(Y9, Y22, Y23, Y25)

	CHAIN_SQUARE_NORMALIZE_5(Y5, Y6, Y7, Y8, Y9, Y24, Y10, Y11, Y12, Y13, Y14, Y25)

	VMOVDQA64 Y5, Y0
	VMOVDQA64 Y6, Y1
	VMOVDQA64 Y7, Y2
	VMOVDQA64 Y8, Y3
	VMOVDQA64 Y9, Y4
	DECQ AX
	JNZ chain_square_x4_loop

chain_square_x4_store:
	VMOVDQU64 Y0,   0(DI)
	VMOVDQU64 Y1,  32(DI)
	VMOVDQU64 Y2,  64(DI)
	VMOVDQU64 Y3,  96(DI)
	VMOVDQU64 Y4, 128(DI)
	VZEROUPPER
	RET

// func ifmaRepeatedSquareNormalizedX8(out, x *LimbsX8, count int)
//
// Z0..Z4 retain the running field element across every iteration. Z5..Z13
// are low convolution accumulators, Z14..Z22 are high accumulators, Z23 is
// fold scratch, and Z24/Z25 retain the limb mask and fold constant. Nothing
// is stored until the entire dependent chain is complete.
TEXT ·ifmaRepeatedSquareNormalizedX8(SB), NOSPLIT, $0-24
	MOVQ out+0(FP), DI
	MOVQ x+8(FP), CX
	MOVQ count+16(FP), AX

	VMOVDQU64   0(CX), Z0
	VMOVDQU64  64(CX), Z1
	VMOVDQU64 128(CX), Z2
	VMOVDQU64 192(CX), Z3
	VMOVDQU64 256(CX), Z4
	TESTQ AX, AX
	JE chain_square_store

	VPBROADCASTQ ·ifmaLimbMask51(SB), Z24
	VPBROADCASTQ ·ifmaFold19(SB), Z25

chain_square_loop:
	CHAIN_SQUARE_CLEAR(Z5)
	CHAIN_SQUARE_CLEAR(Z6)
	CHAIN_SQUARE_CLEAR(Z7)
	CHAIN_SQUARE_CLEAR(Z8)
	CHAIN_SQUARE_CLEAR(Z9)
	CHAIN_SQUARE_CLEAR(Z10)
	CHAIN_SQUARE_CLEAR(Z11)
	CHAIN_SQUARE_CLEAR(Z12)
	CHAIN_SQUARE_CLEAR(Z13)
	CHAIN_SQUARE_CLEAR(Z14)
	CHAIN_SQUARE_CLEAR(Z15)
	CHAIN_SQUARE_CLEAR(Z16)
	CHAIN_SQUARE_CLEAR(Z17)
	CHAIN_SQUARE_CLEAR(Z18)
	CHAIN_SQUARE_CLEAR(Z19)
	CHAIN_SQUARE_CLEAR(Z20)
	CHAIN_SQUARE_CLEAR(Z21)
	CHAIN_SQUARE_CLEAR(Z22)

	CHAIN_SQUARE_MUL_PAIR(Z0, Z1, Z6,  Z15)
	CHAIN_SQUARE_MUL_PAIR(Z0, Z2, Z7,  Z16)
	CHAIN_SQUARE_MUL_PAIR(Z0, Z3, Z8,  Z17)
	CHAIN_SQUARE_MUL_PAIR(Z0, Z4, Z9,  Z18)
	CHAIN_SQUARE_MUL_PAIR(Z1, Z2, Z8,  Z17)
	CHAIN_SQUARE_MUL_PAIR(Z1, Z3, Z9,  Z18)
	CHAIN_SQUARE_MUL_PAIR(Z1, Z4, Z10, Z19)
	CHAIN_SQUARE_MUL_PAIR(Z2, Z3, Z10, Z19)
	CHAIN_SQUARE_MUL_PAIR(Z2, Z4, Z11, Z20)
	CHAIN_SQUARE_MUL_PAIR(Z3, Z4, Z12, Z21)

	VPSLLQ $1, Z6,  Z6
	VPSLLQ $1, Z7,  Z7
	VPSLLQ $1, Z8,  Z8
	VPSLLQ $1, Z9,  Z9
	VPSLLQ $1, Z10, Z10
	VPSLLQ $1, Z11, Z11
	VPSLLQ $1, Z12, Z12
	VPSLLQ $1, Z15, Z15
	VPSLLQ $1, Z16, Z16
	VPSLLQ $1, Z17, Z17
	VPSLLQ $1, Z18, Z18
	VPSLLQ $1, Z19, Z19
	VPSLLQ $1, Z20, Z20
	VPSLLQ $1, Z21, Z21

	CHAIN_SQUARE_MUL_PAIR(Z0, Z0, Z5,  Z14)
	CHAIN_SQUARE_MUL_PAIR(Z1, Z1, Z7,  Z16)
	CHAIN_SQUARE_MUL_PAIR(Z2, Z2, Z9,  Z18)
	CHAIN_SQUARE_MUL_PAIR(Z3, Z3, Z11, Z20)
	CHAIN_SQUARE_MUL_PAIR(Z4, Z4, Z13, Z22)

	CHAIN_SQUARE_COMBINE_HIGH(Z14, Z6)
	CHAIN_SQUARE_COMBINE_HIGH(Z15, Z7)
	CHAIN_SQUARE_COMBINE_HIGH(Z16, Z8)
	CHAIN_SQUARE_COMBINE_HIGH(Z17, Z9)
	CHAIN_SQUARE_COMBINE_HIGH(Z18, Z10)
	CHAIN_SQUARE_COMBINE_HIGH(Z19, Z11)
	CHAIN_SQUARE_COMBINE_HIGH(Z20, Z12)
	CHAIN_SQUARE_COMBINE_HIGH(Z21, Z13)
	VPSLLQ $1, Z22, Z22

	CHAIN_SQUARE_FOLD_MUL19(Z5, Z10, Z23, Z25)
	CHAIN_SQUARE_FOLD_MUL19(Z6, Z11, Z23, Z25)
	CHAIN_SQUARE_FOLD_MUL19(Z7, Z12, Z23, Z25)
	CHAIN_SQUARE_FOLD_MUL19(Z8, Z13, Z23, Z25)
	CHAIN_SQUARE_FOLD_MUL19(Z9, Z22, Z23, Z25)

	CHAIN_SQUARE_NORMALIZE_5(Z5, Z6, Z7, Z8, Z9, Z24, Z10, Z11, Z12, Z13, Z14, Z25)

	VMOVDQA64 Z5, Z0
	VMOVDQA64 Z6, Z1
	VMOVDQA64 Z7, Z2
	VMOVDQA64 Z8, Z3
	VMOVDQA64 Z9, Z4
	DECQ AX
	JNZ chain_square_loop

chain_square_store:
	VMOVDQU64 Z0,   0(DI)
	VMOVDQU64 Z1,  64(DI)
	VMOVDQU64 Z2, 128(DI)
	VMOVDQU64 Z3, 192(DI)
	VMOVDQU64 Z4, 256(DI)
	VZEROUPPER
	RET
